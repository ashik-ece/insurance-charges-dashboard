"""
Data preparation for the Medical Cost dashboard (Mini-Project 2).

Reads the raw Kaggle "Medical Cost Personal Datasets" file (data/insurance.csv),
validates it, derives ordinal columns used by the dashboard, and writes
data/insurance_clean.csv for Tableau.

Source: https://www.kaggle.com/datasets/mirichoi0218/insurance
Usage:  python3 prep_data.py
"""

import json
from pathlib import Path

import pandas as pd

DATA_DIR = Path(__file__).parent / "data"
RAW_PATH = DATA_DIR / "insurance.csv"
CLEAN_PATH = DATA_DIR / "insurance_clean.csv"
JS_PATH = Path(__file__).parent / "prototype" / "data.js"

# WHO adult BMI bands; order matters because the column is ordinal.
BMI_BINS = [0, 18.5, 25, 30, float("inf")]
BMI_LABELS = ["Underweight", "Normal", "Overweight", "Obese"]

# Dataset covers ages 18-64.
AGE_BINS = [17, 29, 39, 49, 64]
AGE_LABELS = ["18-29", "30-39", "40-49", "50-64"]


def load_raw(path: Path) -> pd.DataFrame:
    """Load the raw CSV and fail loudly on missing values."""
    df = pd.read_csv(path)
    if df.isna().any().any():
        raise ValueError("Raw data contains missing values")
    return df


def add_derived_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Add ordinal BMI category and age group, and tidy categorical labels."""
    df = df.copy()
    df["bmi_category"] = pd.cut(df["bmi"], bins=BMI_BINS, labels=BMI_LABELS, right=False)
    df["age_group"] = pd.cut(df["age"], bins=AGE_BINS, labels=AGE_LABELS)
    df["smoker"] = df["smoker"].map({"yes": "Smoker", "no": "Non-smoker"})
    df["sex"] = df["sex"].str.capitalize()
    df["region"] = df["region"].str.capitalize()
    df["charges"] = df["charges"].round(2)
    return df


def write_js(df: pd.DataFrame, path: Path) -> None:
    """Write the cleaned rows as a JS array for the D3 prototype.

    A plain <script> include works from file:// (fetch/CSV loading does not),
    so the prototype runs by double-clicking prototype/index.html.
    """
    path.parent.mkdir(exist_ok=True)
    rows = df.astype({"bmi_category": str, "age_group": str}).to_dict("records")
    path.write_text(
        "// Generated by prep_data.py from data/insurance_clean.csv. Do not edit.\n"
        f"const INSURANCE_DATA = {json.dumps(rows, separators=(',', ':'))};\n"
    )


def summarize(df: pd.DataFrame) -> None:
    """Print the aggregates that back the three research questions."""
    print(f"Rows: {len(df)}, columns: {len(df.columns)}\n")
    print("RQ1 - mean charges by smoker x age group")
    print(df.pivot_table("charges", "age_group", "smoker", "mean", observed=True).round(0), "\n")
    print("RQ2 - mean charges by BMI category x smoker")
    print(df.pivot_table("charges", "bmi_category", "smoker", "mean", observed=True).round(0), "\n")
    print("RQ3 - mean charges by region x smoker")
    print(df.pivot_table("charges", "region", "smoker", "mean", observed=True).round(0), "\n")
    print("Smoker share by region")
    print((df.groupby("region")["smoker"].apply(lambda s: (s == "Smoker").mean()) * 100).round(1))


def main() -> None:
    df = add_derived_columns(load_raw(RAW_PATH))
    df.to_csv(CLEAN_PATH, index=False)
    write_js(df, JS_PATH)
    print(f"Wrote {CLEAN_PATH} and {JS_PATH}\n")
    summarize(df)


if __name__ == "__main__":
    main()
